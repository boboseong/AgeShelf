def score_keywords(kws: list[tuple[str, int]]) -> list[int]:
    """키워드 [(단어, 가중치)] → 주제 idx 리스트(≤3). 정확 일치, 범용어는 0.4배."""
    sc: collections.Counter = collections.Counter()
    words: dict[int, set] = collections.defaultdict(set)
    total = 0.0
    for w, g in kws:
        total += g
        for p in set(w.split()) | {w}:
            if p not in _DIC:
                continue
            gw = g * (GENERIC_WEIGHT if p in GENERIC else 1.0)
            for ti in _DIC[p]:
                sc[ti] += gw
                words[ti].add(p)
    out = []
    for ti, s in sc.most_common():
        share = s / total if total else 0
        if (s >= 4 and len(words[ti]) >= 2) or s >= 8 or (s >= 3 and share >= 0.08):
            out.append(ti)
    return out[:3]


def topics_from_title(title: str) -> list[int]:
    tt = re.sub(r"[\(\)\[\]:;,.!?~·…'\"=]+", " ", title or "")
    sc: collections.Counter = collections.Counter()
    for w in tt.split():
        for cand in {w, JOSA.sub("", w)}:
            if len(cand) >= 2 and cand not in GENERIC:
                for ti in _DIC.get(cand, []):
                    sc[ti] += 1
    return [ti for ti, _ in sc.most_common(2)]


